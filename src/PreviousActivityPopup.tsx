import { useEffect, useMemo, useState } from "react";
import { Activity, Volume2, VolumeX, X, Download, Share2, Copy, Check, CalendarDays } from "lucide-react";
import type { ActivityEntry } from "./ActivityDigest";

type Props = {
  entries: ActivityEntry[];
  storageKey: string;
  loaded: boolean;
};

function dayKey(date: Date): string {
  return [date.getFullYear(), String(date.getMonth() + 1).padStart(2, "0"), String(date.getDate()).padStart(2, "0")].join("-");
}

function downloadFile(filename: string, content: string, type: string) {
  const blob = new Blob([content], { type });
  const url = URL.createObjectURL(blob);
  const anchor = document.createElement("a");
  anchor.href = url;
  anchor.download = filename;
  document.body.appendChild(anchor);
  anchor.click();
  anchor.remove();
  URL.revokeObjectURL(url);
}

export default function PreviousActivityPopup({ entries, storageKey, loaded }: Props) {
  const today = dayKey(new Date());
  const yesterdayDate = new Date();
  yesterdayDate.setDate(yesterdayDate.getDate() - 1);
  const yesterdayKey = dayKey(yesterdayDate);
  const seenKey = storageKey + "_previous_summary_seen";
  const [open, setOpen] = useState(false);
  const [muted, setMuted] = useState(false);
  const [audioBlocked, setAudioBlocked] = useState(false);
  const [notice, setNotice] = useState("");
  const [copied, setCopied] = useState(false);
  const previousEntries = useMemo(() => entries
    .filter(entry => dayKey(new Date(entry.timestamp)) === yesterdayKey)
    .filter(entry => /^(share|shared|upload|uploaded|download|downloaded|export|exported|save|saved|create|created|add|added|remove|removed|delete|deleted|send|sent|capture|captured|scan|scanned|run|generate|generated|copy|copied|compile|compiled|edit|edited|update|updated|submit|submitted|invite|invited|accept|accepted|reject|rejected|clear|cleared|import|imported|search|searched|explain|explore|explored)\b/i.test(entry.action))
    .sort((a, b) => new Date(a.timestamp).getTime() - new Date(b.timestamp).getTime()), [entries, yesterdayKey]);
  const summaryText = useMemo(() => {
    const dateLabel = yesterdayDate.toLocaleDateString(undefined, { weekday: "long", year: "numeric", month: "long", day: "numeric" });
    if (!previousEntries.length) return "Your Grand-Lumen activity summary for " + dateLabel + ". No meaningful workspace activities were recorded yesterday.";
    return "Your Grand-Lumen activity summary for " + dateLabel + ". " + previousEntries.length + " activities were recorded. " + previousEntries.map((entry, index) => (index + 1) + ". In " + entry.section + ": " + entry.action + ", at " + new Date(entry.timestamp).toLocaleTimeString(undefined, { hour: "numeric", minute: "2-digit" }) + ".").join(" ");
  }, [previousEntries, yesterdayDate.toLocaleDateString()]);
  const reportText = useMemo(() => [
    "GRAND-LUMEN — PREVIOUS DAY ACTIVITY SUMMARY",
    "Date: " + yesterdayDate.toLocaleDateString(),
    "Generated: " + new Date().toLocaleString(),
    "Meaningful activities: " + previousEntries.length,
    "",
    ...(previousEntries.length ? previousEntries.map(entry => new Date(entry.timestamp).toLocaleTimeString() + " — " + entry.section + ": " + entry.action) : ["No meaningful workspace activities were recorded yesterday."]),
    "",
    "Generated by Grand-Lumen"
  ].join("\n"), [previousEntries, yesterdayDate.toLocaleDateString()]);
  const finish = () => {
    localStorage.setItem(seenKey, today);
    setOpen(false);
    if ("speechSynthesis" in window) window.speechSynthesis.cancel();
  };
  useEffect(() => {
    if (!loaded || localStorage.getItem(seenKey) === today) return;
    setOpen(true);
  }, [loaded, seenKey, today]);
  useEffect(() => {
    if (!open || muted || !("speechSynthesis" in window)) return;
    const utterance = new SpeechSynthesisUtterance(summaryText);
    utterance.rate = 1;
    utterance.pitch = 1;
    utterance.onstart = () => setAudioBlocked(false);
    utterance.onerror = event => {
      if (event.error === "not-allowed" || event.error === "audio-busy") setAudioBlocked(true);
    };
    window.speechSynthesis.cancel();
    window.speechSynthesis.speak(utterance);
    const check = window.setTimeout(() => {
      if (window.speechSynthesis.paused || window.speechSynthesis.speaking === false) setAudioBlocked(true);
    }, 900);
    return () => {
      window.clearTimeout(check);
      window.speechSynthesis.cancel();
    };
  }, [open, muted, summaryText]);
  const toggleMute = () => {
    if (!("speechSynthesis" in window)) {
      setMuted(true);
      setAudioBlocked(true);
      return;
    }
    if (muted) {
      setMuted(false);
      setAudioBlocked(false);
    } else {
      window.speechSynthesis.cancel();
      setMuted(true);
    }
  };
  const playAudio = () => {
    if (!("speechSynthesis" in window)) {
      setAudioBlocked(true);
      return;
    }
    setMuted(false);
    setAudioBlocked(false);
    window.speechSynthesis.cancel();
    const utterance = new SpeechSynthesisUtterance(summaryText);
    utterance.rate = 1;
    utterance.onstart = () => setAudioBlocked(false);
    utterance.onerror = () => setAudioBlocked(true);
    window.speechSynthesis.speak(utterance);
  };
  const copyReport = async () => {
    try {
      await navigator.clipboard.writeText(reportText);
      setCopied(true);
      setNotice("Summary copied.");
      window.setTimeout(() => setCopied(false), 1800);
    } catch {
      setNotice("Clipboard access is unavailable in this browser.");
    }
  };
  const shareReport = async () => {
    if (navigator.share) {
      try {
        await navigator.share({ title: "Grand-Lumen Previous Activity Summary", text: reportText });
      } catch (error) {
        if (error instanceof Error && error.name !== "AbortError") setNotice("Sharing could not be completed.");
      }
    } else {
      await copyReport();
      setNotice("Sharing is unavailable here, so the summary was copied instead.");
    }
  };
  if (!open) return null;
  return <div className="previous-summary-backdrop" role="presentation">
    <section className="previous-summary-card" role="dialog" aria-modal="true" aria-labelledby="previous-summary-title">
      <div className="previous-summary-topline"><span><Activity size={14}/> YOUR DAILY RECAP</span><button type="button" onClick={finish} aria-label="Close activity summary"><X size={19}/></button></div>
      <div className="previous-summary-heading"><span className="previous-summary-mark"><CalendarDays size={23}/></span><div><span className="eyebrow">YESTERDAY IN GRAND-LUMEN</span><h2 id="previous-summary-title">Your previous activity.</h2><p>{yesterdayDate.toLocaleDateString(undefined, { weekday: "long", month: "long", day: "numeric", year: "numeric" })}</p></div></div>
      <div className="previous-summary-count"><strong>{previousEntries.length}</strong><span>meaningful {previousEntries.length === 1 ? "activity" : "activities"}</span></div>
      <div className="previous-summary-list">
        {previousEntries.length ? previousEntries.map(entry => <article key={entry.id}><span className="previous-summary-dot"/><div><b>{entry.action}</b><small>{entry.section} · {new Date(entry.timestamp).toLocaleTimeString(undefined, { hour: "numeric", minute: "2-digit" })}</small></div></article>) : <div className="previous-summary-empty">No meaningful activities were recorded yesterday. Your new day is ready when you are.</div>}
      </div>
      <div className="previous-summary-audio"><span>{audioBlocked ? "Tap play if automatic audio was blocked." : muted ? "Audio muted" : "Audio narration"}</span><button type="button" onClick={toggleMute} aria-label={muted ? "Unmute audio" : "Mute audio"}>{muted ? <VolumeX size={17}/> : <Volume2 size={17}/>} {muted ? "Unmute" : "Mute"}</button>{audioBlocked && <button type="button" onClick={playAudio}>Play narration</button>}</div>
      <div className="previous-summary-actions"><button type="button" onClick={() => downloadFile("grand-lumen-previous-activity.txt", reportText, "text/plain;charset=utf-8")}><Download size={15}/> Download</button><button type="button" onClick={() => downloadFile("grand-lumen-previous-activity.json", JSON.stringify({ date: yesterdayKey, activities: previousEntries }, null, 2), "application/json")}><Download size={15}/> Export JSON</button><button type="button" onClick={() => void shareReport()}><Share2 size={15}/> Share</button><button type="button" onClick={() => void copyReport()}>{copied ? <Check size={15}/> : <Copy size={15}/>} {copied ? "Copied" : "Copy"}</button></div>
      {notice && <p className="previous-summary-notice" role="status">{notice}</p>}
      <button className="previous-summary-done" type="button" onClick={finish}>Done for now <Check size={16}/></button>
      <p className="previous-summary-footnote">This recap appears once per day. Your activity history remains available in Activity Digest.</p>
    </section>
  </div>;
}
